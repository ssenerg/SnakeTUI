/// `id`'s standing in `key`; a new player's if they haven't played it.
async fn standing(conn: &mut AnyConnection, id: AccountId, key: RatingKey) -> Result<Standing> {
    let row = sqlx::query(
        "SELECT rating, deviation, games, wins FROM ratings
         WHERE account_id = $1 AND game = $2 AND category = $3",
    )
    .bind(id)
    .bind(key.game.as_str())
    .bind(key.category)
    .fetch_optional(conn)
    .await?;
    row.map_or(Ok(Standing::default()), |row| standing_from(&row, 0))
}

/// Saves `id`'s new `rating` in `key` after a rated round, counting the
/// round and any win. Snake's quick play also goes in the account's own
/// columns, which servers from before step 3 read.
async fn save_standing(
    conn: &mut AnyConnection,
    id: AccountId,
    key: RatingKey,
    rating: Rating,
    won: bool,
) -> Result<()> {
    let row = sqlx::query(
        "INSERT INTO ratings
             (account_id, game, category, rating, deviation, volatility,
              games, wins, draws, rated_at)
         VALUES ($1, $2, $3, $4, $5, NULL, 1, $6, 0, $7)
         ON CONFLICT (account_id, game, category) DO UPDATE SET
             rating = excluded.rating, deviation = excluded.deviation,
             games = ratings.games + 1, wins = ratings.wins + excluded.wins,
             rated_at = excluded.rated_at
         RETURNING games, wins",
    )
    .bind(id)
    .bind(key.game.as_str())
    .bind(key.category)
    .bind(rating.mu)
    .bind(rating.sigma)
    .bind(i64::from(won))
    .bind(now())
    .fetch_one(&mut *conn)
    .await?;
    if key == SNAKE_QUICK {
        sqlx::query(
            "UPDATE accounts SET rating_mu = $2, rating_sigma = $3, games = $4, wins = $5
             WHERE id = $1",
        )
        .bind(id)
        .bind(rating.mu)
        .bind(rating.sigma)
        .bind(row.try_get::<i64, _>(0)?)
        .bind(row.try_get::<i64, _>(1)?)
        .execute(conn)
        .await?;
    }
    Ok(())
}

/// Which steps a database has had. `needs` is the oldest code, by the
/// number of steps it knows, that can still use it: 0 for a step that only
/// adds things. Both databases take these types.
const MIGRATIONS_TABLE: &str = "
CREATE TABLE IF NOT EXISTS schema_migrations (
    version    BIGINT PRIMARY KEY,
    name       TEXT NOT NULL,
    needs      BIGINT NOT NULL,
    applied_at BIGINT NOT NULL
);
";

/// Applies the steps of [`MIGRATIONS`] the database hasn't had, inside the
/// caller's transaction. Refuses a database that newer code has changed in
/// a way this code can't work with.
async fn migrate(conn: &mut AnyConnection, postgres: bool) -> Result<()> {
    sqlx::raw_sql(MIGRATIONS_TABLE).execute(&mut *conn).await?;
    let rows = sqlx::query("SELECT version, needs FROM schema_migrations")
        .fetch_all(&mut *conn)
        .await?;
    let mut applied = HashSet::new();
    let mut needs = 0;
    for row in &rows {
        applied.insert(row.try_get::<i64, _>(0)?);
        needs = needs.max(row.try_get::<i64, _>(1)?);
    }
    let known = MIGRATIONS.len() as i64;
    if needs > known {
        bail!(
            "the database was changed by newer code: it needs code that knows {needs} \
             steps, and this server knows {known}"
        );
    }
    if let Some(&newest) = applied.iter().max()
        && newest > known
    {
        warn!(
            newest,
            known, "the database has steps this server doesn't know; carrying on"
        );
    }
    for (version, step) in (1..).zip(MIGRATIONS) {
        if applied.contains(&version) {
            continue;
        }
        let sql = if postgres { step.postgres } else { step.sqlite };
        sqlx::raw_sql(sql).execute(&mut *conn).await?;
        sqlx::query(
            "INSERT INTO schema_migrations (version, name, needs, applied_at) \
             VALUES ($1, $2, $3, $4)",
        )
        .bind(version)
        .bind(step.name)
        .bind(if step.breaks_older { version } else { 0 })
        .bind(now())
        .execute(&mut *conn)
        .await?;
        info!(version, name = step.name, "database step applied");
    }
    Ok(())
}

