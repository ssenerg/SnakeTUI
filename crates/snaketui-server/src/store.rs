    /// Makes an account, remembered by `key` if there is one; `prefs`
    /// (each game's) and `records` (Snake's) are what the guest had.
    /// `Ok(None)` if the username is taken, ignoring case.
    pub async fn create_account(
        &self,
        username: &str,
        password_hash: &str,
        key: Option<&str>,
        prefs: &[(GameId, String)],
        records: &Records,
    ) -> Result<Option<Account>> {
        // Snake's also go where servers from before step 3 read them.
        let snake = prefs
            .iter()
            .find(|(game, _)| *game == GameId::Snake)
            .map_or("", |(_, text)| text.as_str());
        let mut tx = self.pool.begin().await?;
        let start = Rating::default();
        let created = sqlx::query(
            "INSERT INTO accounts
                 (username, password_hash, config, rating_mu, rating_sigma, created_at, last_seen)
             VALUES ($1, $2, $3, $4, $5, $6, $6)
             RETURNING id",
        )
        .bind(username)
        .bind(password_hash)
        .bind(snake)
        .bind(start.mu)
        .bind(start.sigma)
        .bind(now())
        .fetch_one(&mut *tx)
        .await;
        let id: AccountId = match created {
            Ok(row) => row.try_get(0)?,
            Err(sqlx::Error::Database(e)) if e.is_unique_violation() => return Ok(None),
            Err(e) => return Err(e.into()),
        };
        for (game, text) in prefs {
            sqlx::query(
                "INSERT INTO account_prefs (account_id, game, prefs, updated_at)
                 VALUES ($1, $2, $3, $4)",
            )
            .bind(id)
            .bind(game.as_str())
            .bind(text)
            .bind(now())
            .execute(&mut *tx)
            .await?;
        }
        for (record_key, best) in records.iter() {
            sqlx::query(
                "INSERT INTO account_records (account_id, record_key, best) VALUES ($1, $2, $3)",
            )
            .bind(id)
            .bind(record_key)
            .bind(i64::from(best))
            .execute(&mut *tx)
            .await?;
        }
        if let Some(key) = key {
            link_key(&mut tx, id, key).await?;
            // The key's guest profile now lives in the account.
            sqlx::query("DELETE FROM solo_records WHERE fingerprint = $1")
                .bind(key)
                .execute(&mut *tx)
                .await?;
            sqlx::query("DELETE FROM players WHERE fingerprint = $1")
                .bind(key)
                .execute(&mut *tx)
                .await?;
        }
        tx.commit().await?;
        Ok(Some(Account {
            id,
            username: username.to_string(),
        }))
    }

