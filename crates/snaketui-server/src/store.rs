    async fn the_leaderboard_ranks_accounts_with_enough_games(store: Store) {
        // Plays `games` rated rounds for `who`, ending at rating `mu`.
        let rated = |who: AccountId, mu: f64, games: u32| {
            let store = store.clone();
            async move {
                for i in 0..games {
                    let rating = Rating { mu, sigma: 4.0 };
                    let won = i % 2 == 0;
                    let results = [RatedResult {
                        account: who,
                        rating,
                        won,
                    }];
                    store.save_rated_round(&results).await.unwrap();
                }
            }
        };
        let ann = account(&store, "ann", None).await;
        let ben = account(&store, "ben", None).await;
        let cat = account(&store, "cat", None).await;
        let dan = account(&store, "Dan", None).await;
        rated(ann.id, 26.0, 5).await;
        rated(ben.id, 27.0, 6).await;
        rated(cat.id, 30.0, 4).await; // best, but not enough games
        rated(dan.id, 26.0, 7).await; // ann's rating, more games

        let names = |board: Vec<Ranked>| board.into_iter().map(|r| r.username).collect::<Vec<_>>();
        let board = store.leaderboard(5, 20).await.unwrap();
        assert_eq!(names(board.clone()), ["ben", "Dan", "ann"]);
        assert_eq!((board[0].games, board[0].wins), (6, 3));
        assert_eq!(board[0].rating.mu, 27.0);
        assert_eq!(
            names(store.leaderboard(5, 2).await.unwrap()),
            ["ben", "Dan"]
        );
        assert_eq!(names(store.leaderboard(4, 1).await.unwrap()), ["cat"]);

        assert_eq!(store.place_of(ben.id, 5).await.unwrap(), Some(1));
        assert_eq!(store.place_of(dan.id, 5).await.unwrap(), Some(2));
        assert_eq!(
            store.place_of(ann.id, 5).await.unwrap(),
            Some(3),
            "as listed"
        );
        assert_eq!(store.place_of(cat.id, 5).await.unwrap(), None);
        assert_eq!(store.place_of(cat.id, 4).await.unwrap(), Some(1));
    }

    async fn friendship_needs_both_sides(store: Store) {
        let a = account(&store, "alice", None).await;
        let b = account(&store, "bob", None).await;
        let c = account(&store, "cat", None).await;
        assert_eq!(
            store.request_friend(a.id, b.id).await.unwrap(),
            Requested::Sent
        );
        assert_eq!(
            store.request_friend(a.id, b.id).await.unwrap(),
            Requested::AlreadyAsked
        );
        assert!(!store.are_friends(a.id, b.id).await.unwrap());
        let lists = store.friend_lists(b.id).await.unwrap();
        assert_eq!(lists.incoming[0].username, "alice");
        assert!(store.accept_friend(b.id, a.id).await.unwrap());
        assert!(store.are_friends(a.id, b.id).await.unwrap());
        assert!(
            !store.accept_friend(b.id, a.id).await.unwrap(),
            "no request left"
        );
        assert_eq!(
            store.request_friend(b.id, a.id).await.unwrap(),
            Requested::AlreadyFriends
        );
        // Declining the request after accepting it (from a screen that
        // hadn't caught up) keeps the friendship.
        store.decline_friend(b.id, a.id).await.unwrap();
        assert!(store.are_friends(a.id, b.id).await.unwrap());

        // Asking someone who already asked you makes you friends.
        store.request_friend(c.id, a.id).await.unwrap();
        assert_eq!(
            store.request_friend(a.id, c.id).await.unwrap(),
            Requested::NowFriends
        );
        let names: Vec<String> = store
            .friend_lists(a.id)
            .await
            .unwrap()
            .friends
            .into_iter()
            .map(|f| f.username)
            .collect();
        assert_eq!(names, ["bob", "cat"]);

        store.unfriend(a.id, b.id).await.unwrap();
        assert!(!store.are_friends(b.id, a.id).await.unwrap());

        // Declining a request drops it, and only it.
        store.request_friend(c.id, b.id).await.unwrap();
        store.decline_friend(b.id, c.id).await.unwrap();
        let lists = store.friend_lists(b.id).await.unwrap();
        assert!(lists.incoming.is_empty() && lists.friends.is_empty());
        assert!(store.friend_lists(c.id).await.unwrap().outgoing.is_empty());
    }

    async fn asking_back_respects_the_friend_limit(store: Store) {
        let a = account(&store, "alice", None).await;
        for i in 0..MAX_FRIENDS {
            let other = account(&store, &format!("f{i}"), None).await;
            store.request_friend(other.id, a.id).await.unwrap();
            assert!(store.accept_friend(a.id, other.id).await.unwrap());
        }
        // Someone asks alice, and she asks them back: that would be one
        // friend too many.
        let late = account(&store, "late", None).await;
        assert_eq!(
            store.request_friend(late.id, a.id).await.unwrap(),
            Requested::Sent
        );
        assert_eq!(
            store.request_friend(a.id, late.id).await.unwrap(),
            Requested::TooMany
        );
        assert!(!store.are_friends(a.id, late.id).await.unwrap());
        let lists = store.friend_lists(a.id).await.unwrap();
        let incoming: Vec<&str> = lists.incoming.iter().map(|f| f.username.as_str()).collect();
        assert_eq!(incoming, ["late"], "their request still waits");
    }

